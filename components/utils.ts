/**
 * Centralized error mapping for Google API errors
 * Maps HTTP status codes to appropriate tRPC error codes
 */
function mapApiErrorToTRPC(error: ApiError): TRPCError {
  const statusCodeMap: Record<
    number,
    'BAD_REQUEST' | 'NOT_FOUND' | 'CONFLICT' | 'PRECONDITION_FAILED'
  > = {
    400: 'BAD_REQUEST',
    404: 'NOT_FOUND',
    409: 'CONFLICT',
    412: 'PRECONDITION_FAILED',
  };

  const code = statusCodeMap[error.status] || 'INTERNAL_SERVER_ERROR';

  // Extract clean error message from Google API error
  // Google API errors come as JSON strings like: {"error":{"code":400,"message":"..."}}
  let parsedMessage = error.message;
  try {
    const parsed = JSON.parse(error.message);
    if (parsed.error?.message) {
      parsedMessage = parsed.error.message;
    }
  } catch {
    parsedMessage = error.message;
  }

  return new TRPCError({
    code,
    message: parsedMessage,
  });
}

/**
 * Valid tRPC error codes that can be used in services
 * Reference: https://trpc.io/docs/server/error-handling
 */
const VALID_TRPC_ERROR_CODES: readonly TRPC_ERROR_CODE_KEY[] = [
  'PARSE_ERROR',
  'BAD_REQUEST',
  'INTERNAL_SERVER_ERROR',
  'UNAUTHORIZED',
  'FORBIDDEN',
  'NOT_FOUND',
  'METHOD_NOT_SUPPORTED',
  'TIMEOUT',
  'CONFLICT',
  'PRECONDITION_FAILED',
  'PAYLOAD_TOO_LARGE',
  'UNPROCESSABLE_CONTENT',
  'TOO_MANY_REQUESTS',
  'CLIENT_CLOSED_REQUEST',
];

/**
 * Type guard to check if a value is a valid TRPC error code
 */
function isTRPCErrorCode(code: unknown): code is TRPC_ERROR_CODE_KEY {
  return typeof code === 'string' && VALID_TRPC_ERROR_CODES.includes(code as TRPC_ERROR_CODE_KEY);
}

/** Message shown to the client when a raw DB/driver error is detected (never leak SQL or params). */
const INTERNAL_ERROR_MESSAGE = 'Something went wrong. Please try again.';

/** Detect raw database/driver error messages that must not be sent to the client. */
function isRawDatabaseError(message: string): boolean {
  return message.startsWith('Failed query:') || message.includes('params:');
}

/**
 * Walk Error#cause for a postgres.js / driver error with a SQLSTATE `code` and a
 * safe public `message` (no query text). Used in dev so tRPC is not a dead end
 * when Drizzle only exposes "Failed query: …".
 */
function postgresSafeDetailFromErrorChain(error: unknown): string | undefined {
  if (process.env.NODE_ENV === 'production') return undefined;
  const seen = new Set<unknown>();
  let cur: unknown = error;
  for (let depth = 0; depth < 10 && cur !== undefined && cur !== null; depth++) {
    if (typeof cur !== 'object') break;
    if (seen.has(cur)) break;
    seen.add(cur);
    if (!(cur instanceof Error)) break;
    const code = (cur as { code?: unknown }).code;
    const msg = typeof cur.message === 'string' ? cur.message.trim() : '';
    const isPgState = typeof code === 'string' && code.length === 5 && /^[0-9A-Z]{5}$/i.test(code);
    if (isPgState && msg && !msg.startsWith('Failed query:') && !msg.includes('params:')) {
      return `${msg} (PostgreSQL ${String(code).toUpperCase()})`;
    }
    cur = cur.cause;
  }
  return undefined;
}

/** `EngineError` from amortization-engine — checked structurally to avoid importing that module here (utils is used from the client via `cn`). */
function isAmortizationEngineError(
  error: unknown
): error is Error & { code: 'INVALID_INPUT' | 'VARIABLE_RATE_NOT_IMPLEMENTED' } {
  if (!(error instanceof Error) || error.name !== 'EngineError') return false;
  const code = (error as { code?: unknown }).code;
  return code === 'INVALID_INPUT' || code === 'VARIABLE_RATE_NOT_IMPLEMENTED';
}

const AMORTIZATION_ENGINE_USER_MESSAGES = {
  invalidInput: {
    en: 'The loan inputs do not produce a valid amortization plan. Check duration, payment frequency, pre-amortization and rates.',
    it: 'I dati del mutuo non producono un piano di ammortamento valido. Controlla durata, periodicità, preammortamento e tassi.',
  },
  variableRateNotImplemented: {
    en: 'The requested variable rate type is not yet supported.',
    it: 'Il tipo di tasso variabile richiesto non è ancora supportato.',
  },
} as const;

function amortizationEngineUserMessage(
  locale: Locale,
  code: 'INVALID_INPUT' | 'VARIABLE_RATE_NOT_IMPLEMENTED'
): string {
  const pack =
    code === 'VARIABLE_RATE_NOT_IMPLEMENTED'
      ? AMORTIZATION_ENGINE_USER_MESSAGES.variableRateNotImplemented
      : AMORTIZATION_ENGINE_USER_MESSAGES.invalidInput;
  return pack[locale];
}

export type HandleApiErrorOptions = {
  /** When set (e.g. from tRPC `ctx.locale`), user-facing copy matches the active UI language. */
  locale?: Locale;
};

/**
 * Centralized error handler for external API errors
 * Always wraps errors in TRPCError and never leaks raw errors to client
 */

export function handleApiError(
  error: ApiError | Error | unknown,
  opts?: HandleApiErrorOptions
): never {
  const locale = opts?.locale ?? defaultLocale;
  if (error instanceof ApiError) {
    throw mapApiErrorToTRPC(error);
  }

  // Re-throw TRPCError as-is (e.g. from context or procedure)
  if (error instanceof TRPCError) {
    throw error;
  }

  // Amortization / planning engine — must precede generic Error (EngineError extends Error).
  if (isAmortizationEngineError(error)) {
    const message = amortizationEngineUserMessage(
      locale,
      error.code === 'VARIABLE_RATE_NOT_IMPLEMENTED'
        ? 'VARIABLE_RATE_NOT_IMPLEMENTED'
        : 'INVALID_INPUT'
    );
    throw new TRPCError({ code: 'BAD_REQUEST', message });
  }

  if (error instanceof Error) {
    const code = isTRPCErrorCode(error.cause) ? error.cause : 'INTERNAL_SERVER_ERROR';
    const pgDevDetail = isRawDatabaseError(error.message)
      ? postgresSafeDetailFromErrorChain(error)
      : undefined;
    const message = isRawDatabaseError(error.message)
      ? (pgDevDetail ?? INTERNAL_ERROR_MESSAGE)
      : error.message;
    if (isRawDatabaseError(error.message)) {
      console.error('[handleApiError] Internal error (sanitized for client):', error.message);
      // Drizzle wraps the real driver error (e.g. PostgresError with .code / .detail)
      // in `error.cause`. Surface it so DB failures are actually debuggable in dev.
      if (error.cause && error.cause !== error) {
        console.error('[handleApiError] Underlying cause:', error.cause);
      }
    } else if (process.env.NODE_ENV !== 'production') {
      // In dev, log any Error that reaches this handler so 500s are never
      // silent. The message is still passed through to the client as-is
      // (non-raw errors are considered safe to expose).
      console.error('[handleApiError] Error passed through:', error);
      if (error.cause && error.cause !== error) {
        console.error('[handleApiError] Underlying cause:', error.cause);
      }
    }
    throw new TRPCError({ code, message });
  }

  throw new TRPCError({
    code: 'INTERNAL_SERVER_ERROR',
    message: 'Unknown error',
  });
}

