export function formatShortDate(iso: string): string {
  return new Date(iso)
    .toLocaleDateString('en-GB', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    })
    .toLowerCase();
}

export function getInitialsForHome(label: string): string {
  const initials = label
    .split(/[\s.]+/)
    .filter((word) => word.length > 1)
    .slice(0, 2)
    .map((word) => word[0])
    .join('')
    .toUpperCase();

  return initials || label.slice(0, 2).toUpperCase();
}

export function splitLegacyPlaceholderInner(inner: string): { base: string; lag: PeriodLag } {
  const s = inner.trim();
  const mLag = s.match(/^(.+?)\s+t-([1-3])\s*$/i);
  if (mLag) return { base: mLag[1]!.trim(), lag: Number(mLag[2]!) as PeriodLag };
  const mT = s.match(/^(.+?)\s+t\s*$/i);
  if (mT) return { base: mT[1]!.trim(), lag: 0 };
  return { base: s, lag: 0 };
}

export function resolveVariableKeyFromLegacyBase(base: string): string {
  const trimmed = base.trim();
  if (VARIABLES.some((v) => v.key === trimmed)) return trimmed;
  const n = trimmed.toLowerCase();
  if (LEGACY_LABEL_TO_KEY[n]) return LEGACY_LABEL_TO_KEY[n]!;
  const byLabel = VARIABLES.find((v) => v.label.toLowerCase() === n);
  return byLabel?.key ?? trimmed;
}

export function legacyDoubleBracesToSingleBrace(formula: string): string {
  return formula.replace(/\{\{([^}]+)\}\}/g, (_, inner: string) => {
    const { base, lag } = splitLegacyPlaceholderInner(inner);
    const key = resolveVariableKeyFromLegacyBase(base);
    if (lag === 0) return `{${key}|t}`;
    return `{${key}|t-${lag}}`;
  });
}

export function parseVarInner(inner: string): { key: string; lag: VarPeriod } {
  const pipe = inner.indexOf('|');
  if (pipe === -1) return { key: inner.trim(), lag: null };
  const key = inner.slice(0, pipe).trim();
  const suf = inner.slice(pipe + 1).trim();
  if (suf === 't') return { key, lag: 0 };
  const m = suf.match(/^t-(\d)$/);
  if (m) {
    const n = parseInt(m[1]!);
    return { key, lag: (n >= 0 && n <= 3 ? n : null) as VarPeriod };
  }
  return { key, lag: null };
}

export function tryCanonicalPlaceholderToDisplay(inner: string): string | null {
  const trimmed = inner.trim();
  const { key, lag } = parseVarInner(trimmed);
  if (!/^[a-z_][a-z0-9_]*$/i.test(key)) return null;
  const meta = VARIABLES.find((v) => v.key === key);
  if (!meta) return null;
  const label = meta.label;
  if (lag === null) return label;
  if (lag === 0) return `${label} t`;
  return `${label} t-${lag}`;
}

export function mergeAdjacentText(pieces: FormulaPiece[]): FormulaPiece[] {
  const out: FormulaPiece[] = [];
  for (const p of pieces) {
    const last = out[out.length - 1];
    if (p.type === 'text' && last?.type === 'text') {
      out[out.length - 1] = { type: 'text', value: last.value + p.value };
    } else {
      out.push(p);
    }
  }
  return out;
}

export function ensureTextPieces(pieces: FormulaPiece[]): FormulaPiece[] {
  if (pieces.length === 0) return [{ type: 'text', value: '' }];
  return mergeAdjacentText(pieces);
}

export function piecesToFormula(pieces: FormulaPiece[]): string {
  return pieces
    .map((p) => {
      if (p.type === 'text') return p.value;
      if (p.lag === null) return `{${p.key}}`;
      if (p.lag === 0) return `{${p.key}|t}`;
      return `{${p.key}|t-${p.lag}}`;
    })
    .join('');
}

export function formulaToPieces(formula: string): FormulaPiece[] {
  if (!formula) return [{ type: 'text', value: '' }];
  const normalized = legacyDoubleBracesToSingleBrace(formula);
  const pieces: FormulaPiece[] = [];
  const re = /\{([^}]+)\}/g;
  let lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = re.exec(normalized)) !== null) {
    if (m.index > lastIndex)
      pieces.push({ type: 'text', value: normalized.slice(lastIndex, m.index) });
    const { key, lag } = parseVarInner(m[1]!);
    const meta = VARIABLES.find((v) => v.key === key);
    pieces.push({ type: 'var', key, label: meta?.label ?? key, lag });
    lastIndex = re.lastIndex;
  }
  if (lastIndex < normalized.length)
    pieces.push({ type: 'text', value: normalized.slice(lastIndex) });
  return ensureTextPieces(pieces);
}

export function nextId(items: FormulaItem[]): string {
  const max = items.reduce((m, i) => Math.max(m, parseInt(i.id, 10) || 0), 0);
  return String(max + 1);
}

export function nextCategoryId(categories: CategoryItem[]): string {
  const max = categories.reduce((m, c) => {
    const n = parseInt(c.id.replace(/\D/g, '') || '0', 10);
    return c.id.startsWith('cat-') ? Math.max(m, n) : m;
  }, 0);
  return `cat-${max + 1}`;
}
