/**
 * Convert File to base64 string for tRPC transmission
 */
export function fileToBase64(file: File): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.readAsDataURL(file);
    reader.onload = () => resolve(reader.result as string);
    reader.onerror = (error) => reject(error);
  });
}

export function formatBytes(bytes: number): string {
  if (bytes === 0) return '0 Bytes';

  const k = 1024;
  const sizes = ['Bytes', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));

  return Math.round((bytes / Math.pow(k, i)) * 100) / 100 + ' ' + sizes[i];
}

/**
 * Splits text at cursor and returns the trailing token query.
 * Useful for mention/autocomplete style inputs.
 */
export function segmentBeforeCursor(
  text: string,
  cursor: number
): { prefix: string; query: string } {
  const before = text.slice(0, cursor);
  const query = before.match(/([a-zA-Z0-9_.]*)$/)?.[1] ?? '';
  return { prefix: before.slice(0, before.length - query.length), query };
}

const pad2 = (n: number) => String(n).padStart(2, '0');

/**
 * Format a Date as YYYY-MM-DD using local date parts (no timezone shift).
 * Use this whenever the calendar date is what matters.
 */
function toDateOnlyString(date: Date): string {
  const y = date.getFullYear();
  const m = date.getMonth() + 1;
  const d = date.getDate();
  return `${y}-${pad2(m)}-${pad2(d)}`;
}

/**
 * Format a Date for API payload: same calendar date with time 00:00:00 UTC.
 * Prevents off-by-one when the server parses the date (e.g. select 10 → send 10, not 9).
 */
export function toApiDateString(date: Date): string {
  return `${toDateOnlyString(date)}T00:00:00.000Z`;
}

/**
 * Normalize an ISO date string from the API to YYYY-MM-DDT00:00:00.000Z for comparison.
 * Uses UTC date parts so stored date (e.g. 2025-02-10T00:00:00.000Z) compares correctly.
 */
export function normalizeApiDateString(isoOrDateStr: string): string {
  const d = new Date(isoOrDateStr);
  const y = d.getUTCFullYear();
  const m = d.getUTCMonth() + 1;
  const day = d.getUTCDate();
  return `${y}-${pad2(m)}-${pad2(day)}T00:00:00.000Z`;
}

